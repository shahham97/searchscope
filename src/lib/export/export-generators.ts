/**
 * Builds a single complete ZIP archive client-side containing all 7 deliverables:
 * PDF (referenced), 7 CSVs, audit-full.json, report.html, IMPROVEMENTS.md, ROADMAP.md, and generated deployable files.
 */
export async function generateFullZip(report: AuditReport): Promise<Blob> {
  const zip = new JSZip();

  // 1. IMPROVEMENTS.md
  zip.file('IMPROVEMENTS.md', generateImprovementsMd(report));

  // 2. ROADMAP.md
  zip.file('ROADMAP.md', generateRoadmapMd(report));

  // 2b. BRAND FACTS & QUESTIONNAIRE
  const brandFacts = seedBrandFactsFromAudit(report);
  zip.file('brand-facts.json', JSON.stringify(brandFacts, null, 2));
  zip.file('FACTS_NEEDED.md', generateFactsNeededMarkdown(report, brandFacts));

  // 3. audit-full.json
  zip.file('audit-full.json', JSON.stringify(report, null, 2));

  // 4. report.html
  zip.file('report.html', generateStandaloneHtml(report));

  // 5. CSVs folder
  const csvFolder = zip.folder('csv');
  if (csvFolder) {
    const csvs = generateCsvFiles(report);
    for (const [name, content] of Object.entries(csvs)) {
      csvFolder.file(name, content);
    }
  }

  // 6. Generated deployable files folder
  const genFolder = zip.folder('generated');
  if (genFolder) {
    const deployables = generateDeployableFiles(report);
    for (const [name, content] of Object.entries(deployables)) {
      genFolder.file(name, content);
    }
  }

  return await zip.generateAsync({ type: 'blob' });
}
