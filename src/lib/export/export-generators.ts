/**
 * Generates an AI-agent-ready fix plan (IMPROVEMENTS.md)
 * formatted specifically for pasting into Cursor, Antigravity, or Claude Code.
 */
export function generateImprovementsMd(report: AuditReport): string {
  const dateStr = new Date(report.auditDate).toISOString().split('T')[0];

  let md = `# SearchScope AI-Agent Action Plan: ${report.targetDomain} (${dateStr})\n\n`;
  md += `> **Audit Score:** ${report.overallScore}/100 | **Pages Crawled:** ${report.crawlStats.totalPagesCrawled} | **Total Findings:** ${report.findings.length}\n\n`;
  md += `## Instructions for AI Agent (Cursor / Antigravity / Claude Code)\n`;
  md += `You are an expert technical SEO engineer. Execute the following remediation tasks sequentially. For each task, apply the specified code patch to the corresponding codebase file, test the fix, and confirm the acceptance criteria.\n\n`;
  md += `---\n\n`;

  const sortedFindings = [...report.findings].sort((a, b) => {
    const p: Record<string, number> = { critical: 4, high: 3, medium: 2, low: 1, informational: 0 };
    return (p[b.severity] || 0) - (p[a.severity] || 0);
  });

  sortedFindings.forEach((f, idx) => {
    md += `### Task ${idx + 1} [${f.severity.toUpperCase()}]: ${f.title}\n\n`;
    md += `- **Finding ID:** \`${f.id}\`\n`;
    md += `- **Category:** ${f.category}\n`;
    md += `- **Effort:** ${f.effort.replace('_', ' ')}\n`;
    md += `- **Target URL:** \`${f.affectedUrl}\`\n`;
    md += `- **Observed Evidence:** ${f.evidence}\n`;
    md += `- **Why It Matters:** ${f.whyItMatters}\n\n`;
    md += `#### Proposed Remediation\n${f.recommendedFix}\n\n`;

    if (f.implementationExample) {
      const isJson = f.implementationExample.trim().startsWith('{') || f.implementationExample.includes('"@type"');
      const isHtml = f.implementationExample.includes('<');
      const lang = isJson ? 'json' : isHtml ? 'html' : 'typescript';

      md += `#### Code Patch / Snippet\n\`\`\`${lang}\n${f.implementationExample}\n\`\`\`\n\n`;
    }

    md += `#### Acceptance Criteria\n`;
    md += `- [ ] ${f.validationInstructions}\n`;
    md += `- [ ] Re-run SearchScope audit and verify \`${f.id}\` no longer appears in findings.\n\n`;
    md += `---\n\n`;
  });

  return md;
}

/**
 * Generates ROADMAP.md
 */
export function generateRoadmapMd(report: AuditReport): string {
  let md = `# SearchScope Prioritized Action Roadmap: ${report.targetDomain}\n\n`;
  md += `Total tasks: ${report.roadMap.length}\n\n`;

  report.roadMap.forEach((item, idx) => {
    md += `## ${idx + 1}. [${item.impact.toUpperCase()} IMPACT] ${item.title}\n`;
    md += `- **Phase:** ${item.phase.replace(/_/g, ' ')}\n`;
    md += `- **Effort:** ${item.effort.replace(/_/g, ' ')}\n`;
    md += `- **Target:** ${item.affectedUrls.join(', ')}\n`;
    md += `- **Action:** ${item.description}\n`;
    md += `- **Validation:** ${item.validationCheck}\n\n`;
    if (item.codeSnippet) {
      md += `\`\`\`${item.codeSnippet.language}\n${item.codeSnippet.code}\n\`\`\`\n\n`;
    }
  });

  return md;
}

/**
 * Generates auto-generated ready-to-deploy files:
 * corrected robots.txt, sitemap.xml, llms.txt, and jsonld-snippets.json.
 */
export function generateDeployableFiles(report: AuditReport): Record<string, string> {
  const domain = report.targetDomain;
  const origin = report.targetNormalizedUrl;

  // 1. Corrected robots.txt
  const robotsTxt = `# Generated by SearchScope for ${domain}
User-agent: *
Allow: /

# Answer Engine and AI Crawler Directives
User-agent: GPTBot
Allow: /

User-agent: ClaudeBot
Allow: /

User-agent: PerplexityBot
Allow: /

Sitemap: ${origin}/sitemap.xml
`;

  // 2. Ready-to-deploy sitemap.xml
  const validPages = report.pages.filter((p) => p.statusCode === 200 && p.isHtml);
  let sitemapXml = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n`;
  for (const page of validPages) {
    sitemapXml += `  <url>\n    <loc>${page.url}</loc>\n    <lastmod>${new Date().toISOString().split('T')[0]}</lastmod>\n    <changefreq>weekly</changefreq>\n  </url>\n`;
  }
  sitemapXml += `</urlset>\n`;

  // 3. Ready-to-deploy /llms.txt
  let llmsTxt = `# ${report.siteTitle || domain}

> ${report.organizationName || domain} official knowledge manifest for LLMs and AI Agents.

## Primary Sections
- [Home](${origin}): Main landing and offerings overview
`;
  validPages.slice(1, 10).forEach((p) => {
    llmsTxt += `- [${p.title || p.url}](${p.url})\n`;
  });

  // 4. Per-page JSON-LD snippets
  const jsonLdSnippets: Record<string, any> = {
    domain,
    organization: {
      '@context': 'https://schema.org',
      '@type': 'Organization',
      name: report.organizationName || domain,
      url: origin,
      logo: `${origin}/logo.png`,
    },
    webSite: {
      '@context': 'https://schema.org',
      '@type': 'WebSite',
      name: report.siteTitle || domain,
      url: origin,
    },
  };

  return {
    'robots.txt': robotsTxt,
    'sitemap.xml': sitemapXml,
    'llms.txt': llmsTxt,
    'jsonld-snippets.json': JSON.stringify(jsonLdSnippets, null, 2),
  };
}

/**
 * Generates all 7 CSV files as text.
 */
export function generateCsvFiles(report: AuditReport): Record<string, string> {
  // findings.csv
  const findingsHeaders = ['ID', 'Category', 'Severity', 'Title', 'AffectedURL', 'Effort', 'Confidence', 'Evidence', 'Fix'];
  const findingsRows = report.findings.map((f) => [
    `"${f.id}"`,
    f.category,
    f.severity,
    `"${f.title.replace(/"/g, '""')}"`,
    `"${f.affectedUrl}"`,
    f.effort,
    f.confidence,
    `"${f.evidence.replace(/"/g, '""')}"`,
    `"${f.recommendedFix.replace(/"/g, '""')}"`,
  ]);
  const findingsCsv = [findingsHeaders.join(','), ...findingsRows.map((r) => r.join(','))].join('\n');

  // urls.csv
  const urlsHeaders = ['URL', 'StatusCode', 'Title', 'WordCount', 'FetchMs', 'IsHtml', 'Canonical', 'SchemasCount', 'InternalLinks', 'ExternalLinks'];
  const urlsRows = report.pages.map((p) => [
    `"${p.url}"`,
    p.statusCode,
    `"${(p.title || '').replace(/"/g, '""')}"`,
    p.wordCount,
    p.fetchDurationMs,
    p.isHtml,
    `"${p.canonicalUrl || ''}"`,
    p.structuredData.length,
    p.internalLinks.length,
    p.externalLinks.length,
  ]);
  const urlsCsv = [urlsHeaders.join(','), ...urlsRows.map((r) => r.join(','))].join('\n');

  // keywords.csv
  const kwHeaders = ['Keyword', 'Intent', 'Occurrences', 'InTitle', 'InHeading', 'InMeta', 'InBodyOnly', 'TF_IDF_Score'];
  const kwRows = report.keywordCandidates.map((k) => [
    `"${k.keyword}"`,
    k.intent,
    k.occurrenceCount,
    k.inTitleCount,
    k.inHeadingCount,
    k.inMetaCount || 0,
    k.inBodyOnly ? 'Yes' : 'No',
    k.tfIdfScore || 0,
  ]);
  const keywordsCsv = [kwHeaders.join(','), ...kwRows.map((r) => r.join(','))].join('\n');

  // links.csv
  const linksHeaders = ['SourcePage', 'LinkType', 'TargetURL', 'AnchorText'];
  const linksRows: string[][] = [];
  report.pages.forEach((p) => {
    p.internalLinks.forEach((l) => {
      linksRows.push([`"${p.url}"`, 'internal', `"${l.url}"`, `"${l.anchorText.replace(/"/g, '""')}"`]);
    });
    p.externalLinks.forEach((l) => {
      linksRows.push([`"${p.url}"`, 'external', `"${l.url}"`, `"${l.anchorText.replace(/"/g, '""')}"`]);
    });
  });
  const linksCsv = [linksHeaders.join(','), ...linksRows.map((r) => r.join(','))].join('\n');

  // redirects.csv
  const redHeaders = ['FinalURL', 'HopCount', 'HopSequence'];
  const redRows = report.pages
    .filter((p) => (p as any).redirectChain && (p as any).redirectChain.length > 0)
    .map((p) => [`"${p.url}"`, (p as any).redirectChain.length, `"${(p as any).redirectChain.join(' -> ')}"`]);
  const redirectsCsv = [redHeaders.join(','), ...redRows.map((r) => r.join(','))].join('\n');

  // images.csv
  const imgHeaders = ['PageURL', 'ImageSrc', 'HasAlt', 'AltText', 'IsLazy', 'ExplicitDimensions'];
  const imgRows: string[][] = [];
  report.pages.forEach((p) => {
    p.images.forEach((img) => {
      imgRows.push([
        `"${p.url}"`,
        `"${img.src}"`,
        img.hasAlt ? 'Yes' : 'No',
        `"${(img.alt || '').replace(/"/g, '""')}"`,
        img.isLazy ? 'Yes' : 'No',
        img.hasExplicitDimensions ? 'Yes' : 'No',
      ]);
    });
  });
  const imagesCsv = [imgHeaders.join(','), ...imgRows.map((r) => r.join(','))].join('\n');

  // structured-data.csv
  const sdHeaders = ['PageURL', 'SchemaType', 'IsValid', 'Errors', 'Properties'];
  const sdRows: string[][] = [];
  report.pages.forEach((p) => {
    p.structuredData.forEach((sd) => {
      sdRows.push([
        `"${p.url}"`,
        `"${sd.type}"`,
        sd.isValid ? 'Yes' : 'No',
        `"${sd.errors.join('; ').replace(/"/g, '""')}"`,
        `"${sd.propertiesFound.join(', ')}"`,
      ]);
    });
  });
  const structuredDataCsv = [sdHeaders.join(','), ...sdRows.map((r) => r.join(','))].join('\n');

  return {
    'findings.csv': findingsCsv,
    'urls.csv': urlsCsv,
    'keywords.csv': keywordsCsv,
    'links.csv': linksCsv,
    'redirects.csv': redirectsCsv,
    'images.csv': imagesCsv,
    'structured-data.csv': structuredDataCsv,
  };
}

