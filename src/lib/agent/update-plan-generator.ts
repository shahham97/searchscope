import { UpdatePlan, ChangeItem } from './types';

/**
 * Generates an executive, strategic UPDATE_PLAN.md
 */
export function generateUpdatePlanMarkdown(plan: UpdatePlan, domain: string): string {
  const { siteProfile, nicheInsights, changes, qaSummary, factsNeededFromOwner } = plan;

  return `# SearchScope AI Agent Update Plan
## Strategic SEO, AEO & GEO Roadmap for ${domain}
*Generated on ${new Date().toISOString().split('T')[0]} | Powered by SearchScope Autonomous Agent*

---

## 1. Executive Site Profile
- **Domain:** \`${domain}\`
- **Business Type:** ${siteProfile.businessType}
- **Niche & Category:** ${siteProfile.niche} (${siteProfile.subNiche || 'Specialty'})
- **Price Positioning:** ${siteProfile.pricePositioning.replace(/_/g, ' ').toUpperCase()}
- **Brand Voice & Tone:** ${siteProfile.brandVoice.tone}
- **Primary Audience:** ${siteProfile.targetAudience.map((a) => `${a.personaName} (${a.description})`).join(', ')}

### Verified Value Propositions (USPs)
${siteProfile.verifiedUSPs.map((usp) => `- ${usp}`).join('\n')}

---

## 2. Niche & Search Intelligence Insights

### High-Opportunity Topic Clusters
${nicheInsights.topicClusters.map((c) => `- **${c.clusterName}** (${c.intent.toUpperCase()}): Core terms: \`${c.coreTerms.join('`, `')}\`${c.missingFromSite ? ' *(Gap on current site)*' : ''}`).join('\n')}

### Generative Engine Opportunities (GEO / Perplexity / ChatGPT)
${nicheInsights.serpOpportunities.map((s) => `- ${s}`).join('\n')}

### Priority Customer Questions (Answer Engine Optimization)
${nicheInsights.commonQuestions.map((q) => `- "${q.question}"`).join('\n')}

---

## 3. High-Priority Action Backlog (${changes.length} Total Changes)

| ID | Priority | Category | Target URL | Effort | QA Status | Summary of Change |
|----|----------|----------|------------|--------|-----------|-------------------|
${changes
  .map(
    (c) =>
      `| \`${c.id}\` | **${c.priority}** | ${c.category} | \`${c.targetUrl.replace(`https://${domain}`, '') || '/'}\` | ${c.effort} | ${c.qaStatus === 'passed' ? '✅ Passed' : '⚠️ Confirm'} | ${c.rationale.slice(0, 60)}... |`
  )
  .join('\n')}

---

## 4. Owner Confirmation Checklist (${factsNeededFromOwner.length} Items)
> [!IMPORTANT]
> Zero-Hallucination Guardrail: The following attributes could not be confirmed with 100% certainty from the crawled pages. Please confirm these values before pushing changes to production:

${factsNeededFromOwner.length > 0 ? factsNeededFromOwner.map((f, i) => `${i + 1}. [ ] **Confirm:** ${f}`).join('\n') : '_No unverified claims detected. All proposed copy is strictly grounded in crawled page facts._'}

---

## 5. QA Verification Summary
- **Total Proposed Updates:** ${qaSummary.totalItems}
- **Automated QA Passed:** ${qaSummary.passedQa}
- **Flagged for Human Review:** ${qaSummary.flaggedNeedsHuman}
- **Unsupported/Banned Superlatives Intercepted:** ${qaSummary.bannedClaimsIntercepted}

---
*Report generated by SearchScope. No data persisted on server.*
`;
}

/**
 * Generates dev-ready AGENT_TASKS.md with code anchors and unified diffs
 */
export function generateAgentTasksMarkdown(plan: UpdatePlan, domain: string): string {
  const { changes, siteWideChanges, newContentBriefs } = plan;

  let md = `# SearchScope Agent Tasks & Code Patches
## Target: \`${domain}\`
*Dev-friendly tasks with exact file locations, code snippets, and unified diffs.*

---

## Site-Wide Configuration Tasks

### Task S-01: Deploy robots.txt
- **Target File:** \`${changes[0]?.whereToChange.detectedPlatform === 'nextjs_app_router' ? 'src/app/robots.ts (or public/robots.txt)' : 'public/robots.txt'}\`
- **Objective:** Enable generative AI discovery while enforcing crawler policy.

\`\`\`txt
${siteWideChanges.robotsTxt || '# Standard robots.txt'}
\`\`\`

---

### Task S-02: Deploy llms.txt Manifest
- **Target File:** \`public/llms.txt\`
- **Objective:** Provide structured markdown manifest for LLM scrapers and search agents.

\`\`\`markdown
${siteWideChanges.llmsTxt || '# llms.txt'}
\`\`\`

---

### Task S-03: Root Organization Schema
- **Target Location:** Root Layout (\`app/layout.tsx\` or global document \`<head>\`)

\`\`\`html
<script type="application/ld+json">
${siteWideChanges.rootJsonLd || '{}'}
</script>
\`\`\`

---

## Page-by-Page Code Patches & Diffs

`;

  changes.forEach((item, index) => {
    md += `### Task P-${String(index + 1).padStart(2, '0')}: [${item.priority}] ${item.category.toUpperCase()} - \`${item.targetUrl}\`
- **Component / File:** \`${item.whereToChange.suggestedFilePath || 'Page Template'}\`
- **Target Location:** ${item.whereToChange.humanReadable}
- **Platform Guidance:** ${item.whereToChange.platformInstruction}
- **Action Type:** \`${item.changeType.toUpperCase()}\` | **Effort:** \`${item.effort}\` | **Owner:** \`${item.owner}\`
- **Rationale:** ${item.rationale}

#### Unified Diff / Proposed Change:
\`\`\`diff
--- Current (${item.whereToChange.humanReadable})
+++ Proposed
- ${item.current.replace(/\n/g, '\n- ')}
+ ${item.proposed.replace(/\n/g, '\n+ ')}
\`\`\`

${
  item.whereToChange.codeAnchor
    ? `**Code Anchor Reference:**\n\`\`\`typescript\n// In ${item.whereToChange.suggestedFilePath || 'page file'}\n${item.whereToChange.codeAnchor}\n\`\`\`\n`
    : ''
}
${
  item.factsNeeded.length > 0
    ? `> ⚠️ **Facts to Confirm:**\n${item.factsNeeded.map((f) => `> - ${f}`).join('\n')}\n`
    : ''
}
---

`;
  });

  if (newContentBriefs.length > 0) {
    md += `## New Content Creation Tasks\n\n`;
    newContentBriefs.forEach((brief, idx) => {
      md += `### Content Task C-${String(idx + 1).padStart(2, '0')}: "${brief.title}"
- **Suggested Slug:** \`${brief.slug}\`
- **Search Intent:** ${brief.intent}
- **Target Word Count:** ${brief.targetWordCount} words
- **Key Entities to Cover:** \`${brief.entitiesToInclude.join('`, `')}\`

#### Article Outline:
${brief.outline.map((o, i) => `${i + 1}. ${o}`).join('\n')}

#### Starter Draft:
\`\`\`markdown
${brief.initialDraft}
\`\`\`

---
`;
    });
  }

  return md;
}

/**
 * Generates update-plan.csv
 */
export function generateUpdatePlanCsv(plan: UpdatePlan): string {
  const headers = [
    'ID',
    'Priority',
    'Category',
    'Target URL',
    'Change Type',
    'Effort',
    'Impact',
    'QA Status',
    'Owner',
    'Location',
    'Current Content',
    'Proposed Content',
    'Rationale',
    'Facts Needed',
  ];

  const rows = plan.changes.map((c) => [
    c.id,
    c.priority,
    c.category,
    c.targetUrl,
    c.changeType,
    c.effort,
    c.impact,
    c.qaStatus,
    c.owner,
    c.whereToChange.suggestedFilePath || c.whereToChange.humanReadable,
    `"${c.current.replace(/"/g, '""').replace(/\n/g, ' ')}"`,
    `"${c.proposed.replace(/"/g, '""').replace(/\n/g, ' ')}"`,
    `"${c.rationale.replace(/"/g, '""').replace(/\n/g, ' ')}"`,
    `"${c.factsNeeded.join('; ').replace(/"/g, '""')}"`,
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
}

/**
 * Generates the complete Content Pack map for ZIP export
 */
export function generateContentPack(plan: UpdatePlan, domain: string): Record<string, string> {
  const pack: Record<string, string> = {};

  pack['UPDATE_PLAN.md'] = generateUpdatePlanMarkdown(plan, domain);
  pack['AGENT_TASKS.md'] = generateAgentTasksMarkdown(plan, domain);
  pack['update-plan.json'] = JSON.stringify(plan, null, 2);
  pack['update-plan.csv'] = generateUpdatePlanCsv(plan);

  if (plan.siteWideChanges.robotsTxt) {
    pack['content-pack/robots.txt'] = plan.siteWideChanges.robotsTxt;
  }
  if (plan.siteWideChanges.llmsTxt) {
    pack['content-pack/llms.txt'] = plan.siteWideChanges.llmsTxt;
  }
  if (plan.siteWideChanges.rootJsonLd) {
    pack['content-pack/root-organization-schema.json'] = plan.siteWideChanges.rootJsonLd;
  }

  plan.newContentBriefs.forEach((brief, idx) => {
    const filename = `content-pack/brief-${idx + 1}-${brief.slug.replace(/^\//, '').replace(/\//g, '-')}.md`;
    pack[filename] = `# Content Brief: ${brief.title}
**Intent:** ${brief.intent}
**Suggested Slug:** ${brief.slug}
**Target Word Count:** ${brief.targetWordCount}
**Entities:** ${brief.entitiesToInclude.join(', ')}

## Outline
${brief.outline.map((o, i) => `${i + 1}. ${o}`).join('\n')}

## Initial Draft
${brief.initialDraft}
`;
  });

  return pack;
}
